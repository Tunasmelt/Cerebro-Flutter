import 'dart:convert';
import 'dart:typed_data';

import 'package:cerebro_mobile/core/crypto/sealed_crypto.dart';
import 'package:cryptography/cryptography.dart';
import 'package:flutter_test/flutter_test.dart';

List<int> hex(String value) => [
  for (var i = 0; i < value.length; i += 2)
    int.parse(value.substring(i, i + 2), radix: 16),
];

void main() {
  test('rejects empty passphrases like the actual web KDF', () async {
    await expectLater(deriveSealedKey('', Uint8List(16)), throwsArgumentError);
  });

  test(
    'matches web with Unicode, whitespace and a nonzero salt',
    () async {
      const password = '  café 🔒  ';
      final salt = List.generate(16, (i) => i);
      final key = await deriveSealedKey(password, salt);
      final bytes = await key.extractBytes();
      // Independently generated by actual web seal.ts / hash-wasm 4.12.0.
      expect(
        bytes,
        hex('41bfbcd3214c359fe5d7f1c6e9c4f2fae4b7aefbe06ac9d034ff3c64c3834366'),
      );
      final differentSalt = await deriveSealedKey(password, Uint8List(16));
      final differentPassword = await deriveSealedKey('$password!', salt);
      expect(await differentSalt.extractBytes(), isNot(bytes));
      expect(await differentPassword.extractBytes(), isNot(bytes));
    },
    timeout: const Timeout(Duration(minutes: 3)),
  );

  test(
    'matches actual hash-wasm derivation and WebCrypto ciphertext',
    () async {
      // Generated by running web src/lib/crypto/seal.ts, hash-wasm 4.12.0.
      final key = await deriveSealedKey(
        'known-answer-test-passphrase',
        Uint8List(16),
      );
      expect(
        await key.extractBytes(),
        hex('618f4f27fcd47aa29457002646074dfaeecd9a8cc2fa63df9dbba959e2c7ed76'),
      );
      final encrypted = await encryptSealedChunk(
        utf8.encode('known-answer plaintext'),
        key,
        nonce: Uint8List(12),
      );
      expect(
        encrypted.ciphertext,
        hex(
          '9857113140ae53f7cf8fed6a2878ba560f05a3f5cec53ab38be578a2eb17f2a1841f273fbff0',
        ),
      );
      expect(
        await decryptSealedChunk(encrypted, key),
        utf8.encode('known-answer plaintext'),
      );
    },
    timeout: const Timeout(Duration(minutes: 3)),
  );

  test('AES round trip preserves arbitrary bytes and empty content', () async {
    final key = SecretKey(List.generate(32, (i) => i));
    for (final bytes in [<int>[], List.generate(256, (i) => i)]) {
      final sealed = await encryptSealedChunk(
        bytes,
        key,
        nonce: List.filled(12, bytes.isEmpty ? 1 : 2),
      );
      expect(sealed.ciphertext.length, bytes.length + 16);
      expect(await decryptSealedChunk(sealed, key), bytes);
    }
  });

  test(
    'tampered ciphertext, nonce, tag and wrong key fail authentication',
    () async {
      final key = SecretKey(List.filled(32, 3));
      final sealed = await encryptSealedChunk([1, 2, 3], key);
      for (final index in [0, sealed.ciphertext.length - 1]) {
        final changed = List<int>.of(sealed.ciphertext)..[index] ^= 1;
        await expectLater(
          decryptSealedChunk(
            SealedChunk(ciphertext: changed, nonce: sealed.nonce),
            key,
          ),
          throwsA(isA<SecretBoxAuthenticationError>()),
        );
      }
      final nonce = List<int>.of(sealed.nonce)..[0] ^= 1;
      await expectLater(
        decryptSealedChunk(
          SealedChunk(ciphertext: sealed.ciphertext, nonce: nonce),
          key,
        ),
        throwsA(isA<SecretBoxAuthenticationError>()),
      );
      await expectLater(
        decryptSealedChunk(sealed, SecretKey(List.filled(32, 4))),
        throwsA(isA<SecretBoxAuthenticationError>()),
      );
    },
  );

  test('fresh salt per document and fresh nonce per chunk', () async {
    expect(generateSealedSalt(), hasLength(16));
    expect(generateSealedSalt(), isNot(generateSealedSalt()));
    final key = SecretKey(List.filled(32, 5));
    final first = await encryptSealedChunk([1], key);
    final second = await encryptSealedChunk([1], key);
    expect(first.nonce, hasLength(12));
    expect(first.nonce, isNot(second.nonce));
  });

  test('rejects invalid salt, nonce and truncated payload lengths', () async {
    await expectLater(deriveSealedKey('p', [1]), throwsArgumentError);
    final key = SecretKey(List.filled(32, 0));
    await expectLater(
      encryptSealedChunk([1], key, nonce: [1]),
      throwsArgumentError,
    );
    await expectLater(
      decryptSealedChunk(
        SealedChunk(ciphertext: [1], nonce: List.filled(12, 0)),
        key,
      ),
      throwsArgumentError,
    );
  });
}
