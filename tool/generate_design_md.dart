// Regenerates DESIGN.md from the token files and shared widgets, so the design
// record cannot drift from the code:
//
//   dart tool/generate_design_md.dart
//
// test/shared/design_md_test.dart fails if a token or shared widget is missing
// from DESIGN.md, which is the reminder to re-run this.
import 'dart:io';

String read(String path) =>
    File(path).readAsStringSync().replaceAll('\r\n', '\n');

/// `static const NAME = VALUE;` lines with the `//` comment that precedes or
/// trails them.
List<({String name, String value, String note})> constants(String source) {
  final out = <({String name, String value, String note})>[];
  var pending = <String>[];
  for (final raw in source.split('\n')) {
    final line = raw.trim();
    if (line.startsWith('//') && !line.startsWith('///')) {
      pending.add(line.substring(2).trim());
      continue;
    }
    final m = RegExp(
      r'^static const (?:[\w<>]+ )?(\w+) = (.+?);\s*(?://\s*(.*))?$',
    ).firstMatch(line);
    if (m != null) {
      final note = [...pending, if (m.group(3) != null) m.group(3)!].join(' ');
      out.add((name: m.group(1)!, value: m.group(2)!, note: note));
      pending = [];
    } else if (line.isEmpty || line == '}') {
      pending = [];
    }
  }
  return out;
}

String table(List<String> head, List<List<String>> rows) {
  final b = StringBuffer('| ${head.join(' | ')} |\n');
  b.writeln('|${head.map((_) => '---').join('|')}|');
  for (final r in rows) {
    b.writeln('| ${r.map((c) => c.replaceAll('|', r'\|')).join(' | ')} |');
  }
  return b.toString();
}

String hexOf(String value) {
  final m = RegExp(r'Color\(0x([0-9A-Fa-f]{8})\)').firstMatch(value);
  if (m == null) return value; // an alias of another token
  final h = m.group(1)!.toUpperCase();
  final alpha = h.substring(0, 2);
  return alpha == 'FF'
      ? '#${h.substring(2)}'
      : '#${h.substring(2)} @ ${(int.parse(alpha, radix: 16) / 255 * 100).round()}%';
}

String firstDocLine(String source, String className) {
  final lines = source.split('\n');
  final i = lines.indexWhere(
    (l) => RegExp('^(abstract final )?class $className\\b').hasMatch(l),
  );
  if (i <= 0) return '';
  final doc = <String>[];
  for (var j = i - 1; j >= 0 && lines[j].trim().startsWith('///'); j--) {
    doc.insert(0, lines[j].trim().substring(3).trim());
  }
  final text = doc.join(' ').trim();
  final dot = text.indexOf('. ');
  return dot == -1 ? text : text.substring(0, dot + 1);
}

void main() {
  final colors = constants(read('lib/shared/tokens/app_colors.dart'));
  final spacing = constants(read('lib/shared/tokens/app_spacing.dart'));
  final radius = constants(
    read('lib/shared/tokens/app_radius.dart'),
  ).where((c) => !c.name.endsWith('Radius')).toList();
  final type = read('lib/shared/tokens/app_typography.dart');
  final typeSizes = RegExp(
    r'static const (\w+) = TextStyle\(fontSize: (\d+), height: (\d+) / \d+\)',
  ).allMatches(type).toList();
  final families = RegExp(
    r"static const String (fontFamily\w+) = '([^']+)'",
  ).allMatches(type).toList();
  final motion = constants(read('lib/shared/tokens/app_motion.dart'));
  final shadows = RegExp(r'static const List<BoxShadow> (\w+)')
      .allMatches(read('lib/shared/tokens/app_shadows.dart'))
      .map((m) => m.group(1)!)
      .toList();

  final widgetFiles =
      Directory('lib/shared/widgets')
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.dart'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final widgetRows = <List<String>>[];
  for (final f in widgetFiles) {
    final src = read(f.path);
    for (final m in RegExp(
      r'^class (\w+) extends (?:Stateless|Stateful|ConsumerStateful|Consumer Stateless)?\w*Widget',
      multiLine: true,
    ).allMatches(src)) {
      final name = m.group(1)!;
      if (name.startsWith('_')) continue;
      widgetRows.add([
        '`$name`',
        '`${f.path.split(Platform.pathSeparator).last}`',
        firstDocLine(src, name),
      ]);
    }
    for (final m in RegExp(
      r'^Future<\w+> (show\w+)\(',
      multiLine: true,
    ).allMatches(src)) {
      widgetRows.add([
        '`${m.group(1)}()`',
        '`${f.path.split(Platform.pathSeparator).last}`',
        'Function: the app\'s one dialog of this kind.',
      ]);
    }
  }

  final out = StringBuffer();
  out.writeln('# Cerebro Mobile - Design');
  out.writeln();
  out.writeln(
    '> Generated by `dart tool/generate_design_md.dart` from `lib/shared/**`.',
  );
  out.writeln(
    '> Do not edit the tables by hand; edit the tokens and re-run. The prose',
  );
  out.writeln('> sections are in the generator.');
  out.writeln();
  out.writeln('## Direction');
  out.writeln();
  out.writeln(
    'Modernize within the tokens: the web palette, radii and the amber-for-sealed',
  );
  out.writeln(
    'rule stay; hierarchy comes from the type scale and from surface layering',
  );
  out.writeln(
    '(`bgBase` -> `bgElevated` -> `bgRaised`) with 1px low-contrast borders, not from',
  );
  out.writeln(
    'shadows. Glow is for the one primary or pulsing element on a view. Motion is',
  );
  out.writeln(
    'soft (120 / 220 / 360 ms); the sharper pulse curve belongs to the retrieval',
  );
  out.writeln('pulse alone. The graph is 2D on purpose, not as a fallback.');
  out.writeln();
  out.writeln(
    'The typeface is **Plus Jakarta Sans** (bundled) for UI and headings, chosen by',
  );
  out.writeln(
    'the owner as app-only; numbers and labels stay in a monospace face.',
  );
  out.writeln();
  out.writeln('## Rules that are enforced by tests');
  out.writeln();
  out.writeln(
    '- **Amber is for sealed/locked UI only.** No other token may share its value',
  );
  out.writeln('  (`test/shared/app_colors_test.dart`).');
  out.writeln(
    '- **Text contrast** is computed from the tokens (`test/shared/app_contrast_test.dart`):',
  );
  out.writeln(
    '  body text >= 4.5:1 on its surface. The base violet is only 4.11:1 on cards,',
  );
  out.writeln(
    '  so it is for fills, rings and icons; violet *text* uses `accentPrimaryHover`.',
  );
  out.writeln(
    '- **Touch targets are at least 44pt** and **every tappable thing has a label**,',
  );
  out.writeln('  on every main screen, at three sizes and two text scales');
  out.writeln('  (`test/qa/screens_qa_test.dart`).');
  out.writeln(
    '- **Nothing overflows** from a 320px phone to a tablet, at normal and 1.3x text',
  );
  out.writeln('  (same file).');
  out.writeln(
    '- Never call the sealed tier "encrypted" on its own or "zero-knowledge"',
  );
  out.writeln('  (CLAUDE.md naming discipline).');
  out.writeln();
  out.writeln('## Colour');
  out.writeln();
  out.write(
    table(
      ['Token', 'Value', 'Note'],
      [
        for (final c in colors) ['`${c.name}`', hexOf(c.value), c.note],
      ],
    ),
  );
  out.writeln();
  out.writeln('## Spacing');
  out.writeln();
  out.write(
    table(
      ['Token', 'Value'],
      [
        for (final c in spacing)
          ['`${c.name}`', '${c.value.replaceAll('.0', '')} px'],
      ],
    ),
  );
  out.writeln();
  out.writeln('## Radius');
  out.writeln();
  out.write(
    table(
      ['Token', 'Value'],
      [
        for (final c in radius)
          ['`${c.name}`', '${c.value.replaceAll('.0', '')} px'],
      ],
    ),
  );
  out.writeln();
  out.writeln('## Typography');
  out.writeln();
  out.write(
    table(
      ['Family token', 'Face'],
      [
        for (final m in families) ['`${m.group(1)}`', m.group(2)!],
      ],
    ),
  );
  out.writeln();
  out.write(
    table(
      ['Style', 'Size', 'Line height'],
      [
        for (final m in typeSizes)
          ['`${m.group(1)}`', '${m.group(2)} px', '${m.group(3)} px'],
      ],
    ),
  );
  out.writeln();
  out.writeln(
    'Weights: 400 regular, 500 medium, 600 semibold, 700 bold. Numbers (sizes,',
  );
  out.writeln(
    'dates, counts) use `AppTypography.mono(...)` with tabular figures.',
  );
  out.writeln();
  out.writeln('## Motion');
  out.writeln();
  out.write(
    table(
      ['Token', 'Value'],
      [
        for (final c in motion) ['`${c.name}`', '`${c.value}`'],
      ],
    ),
  );
  out.writeln();
  out.writeln('## Elevation');
  out.writeln();
  out.writeln('Soft and diffuse: ${shadows.map((s) => '`$s`').join(', ')}.');
  out.writeln();
  out.writeln('## Shared components (`lib/shared/widgets`)');
  out.writeln();
  out.write(table(['Component', 'File', 'What it is'], widgetRows));
  out.writeln();
  out.writeln('## Patterns');
  out.writeln();
  out.writeln(
    '- **Screen start:** `AppScreenHeader` (title, optional one-line subtitle such as a',
  );
  out.writeln(
    '  count, actions on the right). Tabs share it so they begin the same way.',
  );
  out.writeln(
    '- **Loading:** `AppSkeletonList` (stands still under reduced motion), not a spinner.',
  );
  out.writeln(
    '- **Empty:** `AppEmptyState` with one action; a search that finds nothing says so',
  );
  out.writeln('  and offers to clear.');
  out.writeln(
    '- **Error:** `ErrorView` (compact inline or expanded), announced to screen readers.',
  );
  out.writeln(
    '- **Confirm a destructive action:** `showAppConfirmDialog(destructive: true)`;',
  );
  out.writeln('  red is for destructive actions only.');
  out.writeln(
    '- **Status:** `StatusPill` in the colour that means the state (green done, amber',
  );
  out.writeln('  only for sealed, red failed, teal informational).');
  out.writeln(
    '- **Forms:** `AppTextField` (label above, eye on passwords), inline messages after',
  );
  out.writeln('  a failed submit that clear as the user types.');
  out.writeln(
    '- **Navigation:** five tabs (Docs, Chat, Graph, Board, Settings); a rail at 600px',
  );
  out.writeln('  and wider.');
  out.writeln(
    '- **Graph:** fitted to the screen on open; the legend is also a type filter; zoom',
  );
  out.writeln(
    '  and fit buttons for hands that do not pinch; a List view for screen readers.',
  );
  out.writeln();

  File('DESIGN.md').writeAsStringSync(out.toString());
  stdout.writeln(
    'DESIGN.md: ${colors.length} colours, ${spacing.length} spacing, '
    '${radius.length} radii, ${typeSizes.length} type styles, '
    '${widgetRows.length} components.',
  );
}
